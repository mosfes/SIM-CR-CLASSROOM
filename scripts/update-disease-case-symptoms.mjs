async function main() {
  const codes = Object.keys(caseSymptomsByCode);
  const existingDiseases = await prisma.disease.findMany({
    where: { code: { in: codes } },
    select: { code: true },
  });
  const existingCodes = new Set(existingDiseases.map(({ code }) => code));
  const missingCodes = codes.filter((code) => !existingCodes.has(code));

  if (missingCodes.length > 0) {
    throw new Error(`ไม่พบรหัสโรค: ${missingCodes.join(", ")}`);
  }

  if (process.argv.includes("--dry-run")) {
    process.stdout.write(`ตรวจสอบโจทย์อาการแล้ว ${codes.length} โรค\n`);
    return;
  }

  await prisma.$transaction(
    codes.map((code) =>
      prisma.disease.update({
        where: { code },
        data: { symptoms: caseSymptomsByCode[code] },
      }),
    ),
  );

  process.stdout.write(`อัปเดตอาการตามโจทย์กรณีศึกษาแล้ว ${codes.length} โรค\n`);
}

try {
  await main();
} catch (error) {
  const message = error instanceof Error ? error.message : "อัปเดตอาการของโรคไม่สำเร็จ";
  process.stderr.write(`${message}\n`);
  process.exitCode = 1;
} finally {
  await prisma.$disconnect();
}
